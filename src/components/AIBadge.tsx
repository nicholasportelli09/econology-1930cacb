import { Sparkles } from "lucide-react";

/**
 * Small "AI-generated" label. Show wherever content is produced by an LLM
 * (summaries, digests, market ideas, tutor answers, personalized notes).
 */
export function AIBadge({ label = "AI-generated", className = "" }: { label?: string; className?: string }) {
  return (
    <span
      className={`inline-flex items-center gap-1 rounded-full border border-primary/30 bg-primary/10 px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wider text-primary ${className}`}
      title="This content was generated by an AI model and may be inaccurate."
    >
      <Sparkles size={10} />
      {label}
    </span>
  );
}